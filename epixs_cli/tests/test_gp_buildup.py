@pytest.mark.skipif(not HAS_XCOM, reason="xcom_engine.py not built yet (parallel work)")
def test_zeff_water_matches_classic_low_energy_value():
    from zeff import zeff as zeff_fn

    water = {"H": 0.111898, "O": 0.888102}
    # The classic Zeff(water) ~ 7.4 (Hine 1952 and many later reproductions)
    # is a LOW-ENERGY, photoelectric-dominated value -- NOT a constant across
    # all energies. Zeff(E) is energy-dependent and has a well-documented
    # minimum ("Compton dip") in roughly the 0.1-1.5 MeV range for low-Z,
    # hydrogenous materials like water (confirmed against the effective-Z
    # literature during this project's build, e.g. Zeff(water) is commonly
    # reported to range ~3-8 across the diagnostic-to-MeV energy span). Test
    # the classic value at a low, photoelectric-dominated energy instead of
    # at 1 MeV, where the correct value is ~3.3, not ~7.4 (see the dip test
    # below -- an earlier version of this test wrongly asserted 7.0-7.8 at
    # 1 MeV, which caught a real z1/z2 bracket-ordering bug in zeq() before
    # being corrected to test the right physics at the right energy).
    z = zeff_fn(water, energy_mev=0.02, xcom_engine=xcom_engine)
    assert 5.5 < z < 7.8


@pytest.mark.skipif(not HAS_XCOM, reason="xcom_engine.py not built yet (parallel work)")
def test_zeff_water_has_compton_dip_near_1_mev():
    from zeff import zeff as zeff_fn

    water = {"H": 0.111898, "O": 0.888102}
    z_low = zeff_fn(water, energy_mev=0.02, xcom_engine=xcom_engine)
    z_dip = zeff_fn(water, energy_mev=1.0, xcom_engine=xcom_engine)
    z_high = zeff_fn(water, energy_mev=10.0, xcom_engine=xcom_engine)
    # Compton scattering (mu/rho ~ Z/A, nearly constant except H) dominates
    # water's attenuation from ~0.1-5 MeV, which pulls Zeff down toward the
    # low, roughly Z/A-driven value there; photoelectric (low E) and pair
    # production (high E) both scale more steeply with Z, pulling Zeff back
    # up on either side -- hence the dip, not a monotonic trend.
    assert 3.0 < z_dip < 3.6
    assert z_dip < z_low
    assert z_dip < z_high
