def test_electron_density_water_matches_known_value():
    # Water mass fractions (H2O: A_H=1.008, A_O=15.999):
    #   w_H = 2*1.008 / (2*1.008+15.999) = 0.111898
    #   w_O = 15.999   / (2*1.008+15.999) = 0.888102
    water = {"H": 0.111898, "O": 0.888102}
    ne = electron_density(water, density_g_cm3=1.0)
    # Textbook value for liquid water: ~3.343e23 electrons/cm^3.
    assert ne == pytest.approx(3.343e23, rel=2e-3)


